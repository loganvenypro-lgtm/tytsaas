/** Topic slugs (lowercase Wikipedia slug, as found in topicDetails URLs) -> [[nicheId, weight]] */
export const TOPIC_INDEX = buildTopicIndex();

function buildTopicIndex() {
  const index = new Map();
  for (const niche of NICHES) {
    for (const [slug, weight] of Object.entries(niche.topics)) {
      const key = slug.toLowerCase();
      if (!index.has(key)) index.set(key, []);
      index.get(key).push([niche.id, weight]);
    }
  }
  return index;
}

export const NICHE_BY_ID = Object.fromEntries(NICHES.map((n) => [n.id, n]));
